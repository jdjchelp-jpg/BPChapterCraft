/**
 * Builds a file input accept attribute string covering all supported document extensions
 */
export function getAllAcceptExtensions(): string {
  const exts = new Set<string>();
  ALL_SUPPORTED_DOCUMENT_FORMATS.forEach((fmt) => {
    fmt.extensions.forEach((e) => exts.add(`.${e.toLowerCase()}`));
  });
  // Also common MIME types
  return Array.from(exts).join(',');
}

/**
 * Look up format definition by filename or extension
 */
export function findFormatByExtension(filenameOrExt: string): DocumentFormatDefinition | undefined {
  const ext = filenameOrExt.split('.').pop()?.toLowerCase() || filenameOrExt.toLowerCase();
  return ALL_SUPPORTED_DOCUMENT_FORMATS.find((f) =>
    f.extensions.some((e) => e.toLowerCase() === ext)
  );
}
